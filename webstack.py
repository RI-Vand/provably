"""webstack - audit AND fix the stack most AI-built apps use: Next.js / React / Express with Supabase or Firebase.
audit_web(files) -> findings, fix_web(files) -> (new_files, applied, review, env_required). files = {relative_path: text}. Stdlib only.
Everything here is a pattern rewrite (tested, not Dafny-verified)."""
import json, os, re

CLIENT_HINT = re.compile(r"""^\s*['"]use client['"]""", re.M)
SERVER_ACTION = re.compile(r"""^\s*['"]use server['"]""", re.M)
JS_EXT = (".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs")
PUBLIC_PATH = re.compile(r"(webhook|public|health|ping|status|callback|login|signin|signup|register|logout|auth/|cron|og/|sitemap|robots|\.well-known|csrf|stripe/hook)", re.I)
AUTH_MARK = re.compile(r"(getUser\(|getSession\(|auth\(\)|currentUser\(|getServerSession|getToken\(|verifyIdToken|requireUser|requireAuth|withAuth|authMiddleware|clerkClient|getAuth\(|isAuthenticated|session\??\.user|req\.user\b|ensureAuth)")
SECRET_ENV = re.compile(r"(?:NEXT_PUBLIC|VITE|REACT_APP|PUBLIC)_[A-Z0-9_]*(SERVICE_ROLE|SECRET|PRIVATE|PASSWORD|OPENAI|ANTHROPIC|STRIPE_SK|DATABASE_URL|JWT_SECRET)[A-Z0-9_]*")
OWNER_COL = re.compile(r"^\s*(user_id|owner_id|owner|created_by|author_id|uid|profile_id)\s+uuid", re.I | re.M)
RAND_CTX = re.compile(r"(token|secret|key|otp|code|session|nonce|password|reset|invite|id)", re.I)
HANDLER = re.compile(r"export\s+(?:async\s+)?function\s+(GET|POST|PUT|PATCH|DELETE)\s*\(([^)]*)\)\s*(?::\s*[^{]+)?\{")
ARROW = re.compile(r"export\s+const\s+(GET|POST|PUT|PATCH|DELETE)\s*=\s*(?:async\s*)?\(([^)]*)\)\s*(?::\s*[^=]+)?=>\s*\{")
PAGES_HANDLER = re.compile(r"export\s+default\s+(?:async\s+)?function\s+\w*\s*\(\s*(\w+)\s*(?::\s*[^,)]+)?,\s*(\w+)[^)]*\)\s*\{")


def is_route(path):
    p = path.replace("\\", "/")
    return bool(re.search(r"(^|/)app/.*route\.(ts|js|mjs)$", p) or re.search(r"(^|/)pages/api/", p))


def provider(files):
    pk = " ".join(t for n, t in files.items() if n.endswith("package.json"))
    if "@clerk/" in pk: return "clerk"
    if "next-auth" in pk: return "nextauth"
    if "@supabase" in pk: return "supabase"
    if "firebase" in pk: return "firebase"
    return None


def is_ts(files):
    return any(n.endswith((".ts", ".tsx")) for n in files)


