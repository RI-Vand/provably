def rel_import(frm, to_noext):
    d = os.path.dirname(frm.replace("\\", "/"))
    r = os.path.relpath(to_noext, d or ".").replace("\\", "/")
    return r if r.startswith(".") else "./" + r


def add_import(text, line):
    if line.strip() in text:
        return text
    m = list(re.finditer(r"^(?:import\s.+?;?\s*$)", text, re.M))
    pos = m[-1].end() if m else 0
    if not m:
        d = re.match(r"\s*(['\"]use (?:client|server)['\"];?\s*\n)", text)
        pos = d.end() if d else 0
    return text[:pos] + ("\n" if pos else "") + line + ("\n" if not m and not pos else "") + text[pos:]


