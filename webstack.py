ESC_TS = 'function escapeHtml(s: unknown): string { return String(s).replace(/[&<>"\']/g, (c: string) => (({ "&": "&amp;", "<": "&lt;", ">": "&gt;", \'"\': "&quot;", "\'": "&#39;" }) as Record<string, string>)[c]); }\n'
