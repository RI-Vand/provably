OMIT_FN = 'function omitPrivileged(o) { const bad = /^(id|_id|role|roles|is_?admin|admin|is_?staff|permissions?|owner(_id)?|user_?id|account_?id|balance|credits?|price|total|discount|verified|is_?verified|status|created_?at|updated_?at|password_?hash|tenant(_id)?)$/i; return Object.fromEntries(Object.entries(o || {}).filter(([k]) => !bad.test(k))); }\n'


def audit_web(files):
    _, applied, review, _ = fix_web(files, dry=True)
    return applied + review


def fix_web(files, dry=False):
    files = dict(files)
    applied, review, envs = [], [], []

    def ok(rule, f, desc):
        applied.append({"rule": rule, "file": f, "desc": desc})

    def rv(rule, f, why):
        review.append({"rule": rule, "file": f, "action": why})

    prov, ts = provider(files), is_ts(files)
    helper_path = None
    # ---- 1. env var names that ship secrets to the browser -------------------------------------------------------------------
    renames = {}
    for n, t in files.items():
        if os.path.basename(n).startswith(".env") or n.endswith(JS_EXT) or n.endswith((".json", ".yml", ".yaml", ".toml")):
            for m in SECRET_ENV.finditer(t):
                renames[m.group(0)] = re.sub(r"^(NEXT_PUBLIC|VITE|REACT_APP|PUBLIC)_", "", m.group(0))
    for n in list(files):
        t = files[n]
        for old, new in renames.items():
            if old in t:
                files[n] = t = t.replace(old, new)
                ok("public_secret_env", n, f"{old} -> {new} (no longer sent to the browser; rotate the key, it was exposed)")
    # ---- 2. SQL: row level security ----------------------------------------------------------------------------------------------
    sql = {n: t for n, t in files.items() if n.endswith(".sql")}
    all_sql = "\n".join(sql.values())
    for n, t in sql.items():
        for m in reversed(list(re.finditer(r"create\s+table\s+(?:if\s+not\s+exists\s+)?((?:public\.)?\"?(\w+)\"?)\s*\((.*?)\)\s*;", t, re.I | re.S))):
            full, name, body = m.group(1), m.group(2), m.group(3)
            if re.search(r"alter\s+table\s+(?:public\.)?\"?%s\"?\s+enable\s+row\s+level\s+security" % re.escape(name), all_sql, re.I):
                continue
            col = OWNER_COL.search(body)
            owner = col.group(1) if col else ("id" if re.search(r"\bid\s+uuid[^,]*references\s+auth\.users", body, re.I) else None)
            add = f"\n-- provably: row level security (default deny)\nalter table {full} enable row level security;\n"
            if owner:
                for verb, clause in (("select", "using"), ("insert", "with check"), ("update", "using"), ("delete", "using")):
                    add += f'create policy "{name}_{verb}_own" on {full} for {verb} to authenticated {clause} ((select auth.uid()) = {owner});\n'
                add = add.replace(f'for update to authenticated using ((select auth.uid()) = {owner});', f'for update to authenticated using ((select auth.uid()) = {owner}) with check ((select auth.uid()) = {owner});')
                ok("rls_missing", n, f"{name}: RLS on, each user sees and changes only their own rows ({owner} = auth.uid())")
            else:
                ok("rls_missing", n, f"{name}: RLS on, no policies = nobody but the service role can touch it")
                rv("rls_policy", n, f"{name}: RLS is on with no policies, so the app cannot read it from the browser. Add a policy that states who may see which rows.")
            files[n] = t = t[:m.end()] + add + t[m.end():]
            all_sql = "\n".join(v for v in files.values() if False) or "\n".join(files[k] for k in sql)
        def pol(m):
            stmt = m.group(0)
            tbl = re.search(r"\bon\s+(?:public\.)?\"?(\w+)\"?", stmt, re.I)
            verb = re.search(r"\bfor\s+(all|insert|update|delete|select)\b", stmt, re.I)
            if not (re.search(r"(using|with\s+check)\s*\(\s*true\s*\)", stmt, re.I) and tbl):
                return stmt
            cm = re.search(r"create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?\"?%s\"?\s*\((.*?)\)\s*;" % re.escape(tbl.group(1)), all_sql, re.I | re.S)
            col = OWNER_COL.search(cm.group(1)) if cm else None
            if verb and verb.group(1).lower() == "select":
                rv("rls_open", n, f"{tbl.group(1)}: select policy is open to everyone. If that data is not meant to be public, restrict it.")
                return stmt
            if col:
                new = re.sub(r"(using|with\s+check)\s*\(\s*true\s*\)", lambda x: f"{x.group(1)} ((select auth.uid()) = {col.group(1)})", stmt, flags=re.I)
                ok("rls_open", n, f"{tbl.group(1)}: write policy `true` -> owner only")
                return new
            new = re.sub(r"(using|with\s+check)\s*\(\s*true\s*\)", r"\1 ((select auth.role()) = 'authenticated')", stmt, flags=re.I)
            ok("rls_open", n, f"{tbl.group(1)}: write policy `true` -> signed-in users only")
            rv("rls_owner", n, f"{tbl.group(1)}: no owner column found; any signed-in user can still write any row. Add an owner column and policy.")
            return new
        files[n] = re.sub(r"create\s+policy\b[^;]*;", pol, files[n], flags=re.I | re.S)
    # ---- 3. Firebase rules ------------------------------------------------------------------------------------------------------
    for n, t in list(files.items()):
        if n.endswith(".rules"):
            def rule(m):
                head, stack = t[:m.start()], []
                for tok in re.finditer(r"match\s+(/[^\n{]*(?:\{[^}\n]*\}[^\n{]*)*)\{|\{|\}", head):
                    x = tok.group(0)
                    if x == "}":
                        if stack: stack.pop()
                    elif x == "{":
                        stack.append(None)
                    else:
                        vars_ = re.findall(r"\{(\w+)\}", tok.group(1))
                        stack.append(next((v for v in vars_ if re.search(r"user|uid", v, re.I)), None))
                uid = next((u for u in reversed(stack) if u and re.search(r"user|uid", u, re.I)), None)
                if uid:
                    ok("firebase_rules_open", n, f"`if true` -> only the signed-in owner ({uid})")
                    return m.group(1) + f"request.auth != null && request.auth.uid == {uid}"
                ok("firebase_rules_open", n, "`if true` -> signed-in users only")
                rv("firebase_rules_owner", n, "Any signed-in user can still access every document here. Restrict by owner, e.g. request.auth.uid == resource.data.uid.")
                return m.group(1) + "request.auth != null"
            new = re.sub(r"(allow\s+[^:;\n]+:\s*if\s+)(?:true|request\.time\s*<\s*timestamp\.date\([^)]*\))", rule, t)
            files[n] = new
    # ---- 4. JS / TS files ---------------------------------------------------------------------------------------------------------
    need_helper = False
    for n in list(files):
        if not n.endswith(JS_EXT):
            continue
        t = files[n]
        client = bool(CLIENT_HINT.search(t)) or bool(re.search(r"(^|/)(components|hooks|src/app/[^/]*page)", n.replace("\\", "/"))) and not is_route(n)
        # hard-coded secrets
        def lit(m):
            name, val = m.group(2), m.group(5)
            if not (re.search(r"(secret|token|api_?key|password|private)", name, re.I) or re.match(r"(sk_live|sk-[A-Za-z0-9]{16}|AKIA|ghp_|xox[bp]-|eyJ[A-Za-z0-9_-]{20})", val)):
                return m.group(0)
            if client:
                rv("hardcoded_secret", n, f"{name} is a secret inside browser code; it cannot be fixed by moving it. Rotate it and call the service from a server route.")
                return m.group(0)
            env = re.sub(r"[^A-Z0-9]+", "_", name.upper()).strip("_")
            envs.append(env)
            ok("hardcoded_secret", n, f"{name} moved to process.env.{env} (rotate the old value, it is exposed)")
            return f"{m.group(1)}{name}{m.group(3)}= process.env.{env}"
        t = re.sub(r"""((?:export\s+)?(?:const|let|var)\s+)(\w+)(\s*(?::\s*string\s*)?)=\s*(["'`])([^"'`\n]{12,})\4""", lit, t)
        # weak randomness
        def rnd(m):
            line = t[t.rfind("\n", 0, m.start()) + 1:t.find("\n", m.end())]
            if RAND_CTX.search(line):
                ok("weak_random", n, "Math.random -> crypto.randomUUID")
                return 'globalThis.crypto.randomUUID().replace(/-/g, "")'
            return m.group(0)
        t = re.sub(r"Math\.random\(\)\.toString\(\s*(?:36|16)\s*\)", rnd, t)
        # TLS off
        if re.search(r"rejectUnauthorized\s*:\s*false|NODE_TLS_REJECT_UNAUTHORIZED\s*=\s*['\"]0['\"]", t):
            t = re.sub(r"rejectUnauthorized\s*:\s*false", "rejectUnauthorized: true", t)
            t = re.sub(r"(NODE_TLS_REJECT_UNAUTHORIZED\s*=\s*)['\"]0['\"]", r'\1"1"', t)
            ok("tls_off", n, "certificate checking on")
        # CORS
        origins = '(process.env.CORS_ORIGINS || "").split(",").filter(Boolean)'
        if re.search(r"origin\s*:\s*['\"]\*['\"]", t):
            t = re.sub(r"origin\s*:\s*['\"]\*['\"]", f"origin: {origins}", t); ok("cors_open", n, "only origins listed in CORS_ORIGINS")
        if re.search(r"\bcors\(\s*\)", t):
            t = re.sub(r"\bcors\(\s*\)", f"cors({{ origin: {origins} }})", t); ok("cors_open", n, "only origins listed in CORS_ORIGINS")
        # JWT
        if re.search(r"jwt\.decode\(", t):
            t = re.sub(r"jwt\.decode\(\s*([^,)]+?)\s*(?:,[^)]*)?\)", r'jwt.verify(\1, process.env.JWT_SECRET, { algorithms: ["HS256"] })', t)
            envs.append("JWT_SECRET"); ok("jwt", n, "jwt.decode -> jwt.verify with pinned algorithm")
        if re.search(r"ignoreExpiration\s*:\s*true", t):
            t = re.sub(r"ignoreExpiration\s*:\s*true", "ignoreExpiration: false", t); ok("jwt", n, "expiry enforced")
        if re.search(r"algorithms\s*:\s*\[[^\]]*['\"]none['\"][^\]]*\]", t):
            t = re.sub(r"algorithms\s*:\s*\[[^\]]*\]", 'algorithms: ["HS256"]', t); ok("jwt", n, "alg none removed")
        # XSS
        if "dangerouslySetInnerHTML" in t:
            t2 = re.sub(r"(__html\s*:\s*)(?![\"'`][^\"'`]*[\"'`]\s*\}\})([^}]+?)(\s*\}\})", lambda m: m.group(1) + "escapeHtml(" + m.group(2).strip() + ")" + m.group(3) if not re.search(r"escapeHtml\(|DOMPurify|sanitize", m.group(2)) else m.group(0), t)
            if t2 != t:
                t = t2
                if "function escapeHtml" not in t:
                    t = t.rstrip("\n") + "\n\n" + (ESC_TS if n.endswith((".ts", ".tsx")) else ESC_FN)
                ok("xss", n, "dangerouslySetInnerHTML value HTML-escaped (use DOMPurify if you need real rich HTML)")
        if re.search(r"\.innerHTML\s*=\s*(?![\"'`][^\"'`$]*[\"'`]\s*;)", t):
            t = re.sub(r"\.innerHTML\s*=\s*(?![\"'`][^\"'`$]*[\"'`]\s*;)", ".textContent = ", t); ok("xss", n, "innerHTML -> textContent")
        # open redirect
        def red(m):
            x = m.group(2).strip()
            ok("open_redirect", n, "redirect target must be a same-site path")
            return f'{m.group(1)}((s) => (s.startsWith("/") && !s.startsWith("//") && !s.includes("\\\\") ? s : "/"))(String({x})))'
        t = re.sub(r"((?:res|reply)\.redirect\()\s*((?:req|request)\.(?:query|body|params)[^)]*?)\)", red, t)
        # mass assignment
        if re.search(r"\.(insert|update|upsert|create)\(\s*(req\.body|await\s+request\.json\(\)|body)\s*\)", t):
            t = re.sub(r"\.(insert|update|upsert|create)\(\s*(req\.body|await\s+request\.json\(\)|body)\s*\)", r".\1(omitPrivileged(\2))", t)
            if "function omitPrivileged" not in t:
                t = t.rstrip("\n") + "\n\n" + (OMIT_TS if n.endswith((".ts", ".tsx")) else OMIT_FN)
            ok("mass_assignment", n, "client cannot set role/admin/owner/price/balance/id fields")
        # express hardening
        if re.search(r"express\.json\(\s*\)", t):
            t = re.sub(r"express\.json\(\s*\)", 'express.json({ limit: "1mb" })', t); ok("body_limit", n, "1 MB JSON limit")
        m = re.search(r"^(\s*)(?:const|let|var)\s+(\w+)\s*=\s*express\(\)\s*;?", t, re.M)
        if m and "X-Content-Type-Options" not in t:
            a = m.group(2)
            hdr = (f'\n{m.group(1)}{a}.disable("x-powered-by");\n{m.group(1)}{a}.use((req, res, next) => {{ res.setHeader("X-Content-Type-Options", "nosniff"); res.setHeader("X-Frame-Options", "DENY"); '
                   f'res.setHeader("Referrer-Policy", "no-referrer"); res.setHeader("Content-Security-Policy", "default-src \'self\'; frame-ancestors \'none\'"); next(); }});')
            t = t[:m.end()] + hdr + t[m.end():]; ok("headers", n, "security headers on every response")
        # unauthenticated API routes and server actions
        if prov and is_route(n) and not PUBLIC_PATH.search(n) and not AUTH_MARK.search(t):
            pages = "pages/api" in n.replace("\\", "/")
            changed = False
            if pages:
                def pg(m):
                    return m.group(0) + f'\n  if (!(await requireUser({m.group(1)}))) return {m.group(2)}.status(401).json({{ error: "Unauthorized" }});'
                t2 = PAGES_HANDLER.sub(pg, t)
                changed = t2 != t; t = t2
            else:
                def rt(m):
                    pm = (m.group(2).split(":")[0].strip() or "request")
                    sig = m.group(0)
                    if not m.group(2).strip():
                        sig = sig.replace("()", "(request: Request)" if ts else "(request)", 1); pm = "request"
                    return sig + f'\n  if (!(await requireUser({pm}))) return new Response("Unauthorized", {{ status: 401 }});'
                t2 = ARROW.sub(rt, HANDLER.sub(rt, t))
                changed = t2 != t; t = t2
            if changed:
                need_helper = True
                ok("api_no_auth", n, f"route now requires a signed-in user ({prov}); mark public routes by moving them under a /public/ path")
        elif not prov and is_route(n) and not PUBLIC_PATH.search(n) and not AUTH_MARK.search(t) and HANDLER.search(t) | ARROW.search(t):
            rv("api_no_auth", n, "This API route has no login check and no known auth provider was found in package.json. Add one (Supabase, NextAuth, Clerk or Firebase) and verify the user here.")
        if prov and SERVER_ACTION.search(t) and not AUTH_MARK.search(t):
            def sa(m):
                return m.group(0) + "\n  if (!(await requireUser())) throw new Error(\"Unauthorized\");"
            t2 = re.sub(r"export\s+async\s+function\s+\w+\s*\([^)]*\)\s*(?::\s*[^{]+)?\{", sa, t)
            if t2 != t:
                t = t2; need_helper = True; ok("server_action_no_auth", n, "server action requires a signed-in user")
        # service role key in browser code
        if client and re.search(r"service_role|SERVICE_ROLE", t):
            rv("service_key_in_browser", n, "The Supabase service_role key is used in browser code. It bypasses all row-level security. Remove it from the client and rotate it.")
        files[n] = t
    # add helper + imports once
    if need_helper:
        root = "lib"
        for n in files:
            if n.replace("\\", "/").startswith("src/"):
                root = "src/lib"; break
        helper_path = f"{root}/provably-auth.{'ts' if ts else 'js'}"
        files[helper_path] = helper_source(prov, ts)
        for n in list(files):
            if n.endswith(JS_EXT) and "requireUser(" in files[n] and n != helper_path:
                files[n] = add_import(files[n], f'import {{ requireUser }} from "{rel_import(n, root + "/provably-auth")}";')
    # the helper reads secrets from env
    return files, applied, review, sorted(set(envs))
